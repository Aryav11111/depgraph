"""The parser against real npm output.

tests/fixtures/npm/realworld holds lockfiles generated by npm 10 (node:22-alpine)
from the package.json beside them (`npm install --package-lock-only
--lockfile-version=N`), so they contain whatever real-world quirks npm emits:
hoisting, nested duplicates, optional platform binaries, optional peers.
"""

from collections import Counter, defaultdict
from functools import cache
from pathlib import Path

import pytest

from depgraph.lockfile.npm import ROOT, DepType, LockfileGraph, Source, parse_package_lock

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures" / "npm" / "realworld"


@cache
def graph(version: int) -> LockfileGraph:
    return parse_package_lock((FIXTURES / f"package-lock.v{version}.json").read_bytes())


def test_v2_and_v3_lockfiles_parse_to_the_same_graph():
    v2, v3 = graph(2), graph(3)
    assert (v2.lockfile_version, v3.lockfile_version) == (2, 3)
    assert v2.nodes == v3.nodes
    assert v2.edges == v3.edges
    assert v2.unresolved == v3.unresolved


@pytest.mark.parametrize("version", [2, 3])
def test_structural_invariants(version):
    g = graph(version)
    assert sum(n.source is Source.ROOT for n in g.nodes.values()) == 1
    assert all(e.parent in g.nodes and e.child in g.nodes for e in g.edges)
    assert len({(e.parent, e.child, e.dep_type) for e in g.edges}) == len(g.edges)


def test_every_package_is_reachable_from_the_root():
    g = graph(3)
    children = defaultdict(set)
    for e in g.edges:
        children[e.parent].add(e.child)
    seen, stack = {ROOT}, [ROOT]
    while stack:
        for child in children[stack.pop()] - seen:
            seen.add(child)
            stack.append(child)
    assert seen == set(g.nodes)


def test_only_legitimately_optional_dependencies_are_unresolved():
    g = graph(3)
    assert g.unresolved, "fixture is expected to contain optional peers (e.g. vite -> sass)"
    assert all(not u.required for u in g.unresolved)
    assert ("node_modules/vite", "sass") in {(u.parent, u.name) for u in g.unresolved}


def test_size_and_shape_are_what_npm_produced():
    g = graph(3)
    assert len(g.nodes) == 391  # 390 packages + root
    assert all(n.source in (Source.ROOT, Source.REGISTRY) for n in g.nodes.values())
    types = Counter(e.dep_type for e in g.edges)
    assert types[DepType.DEV] == 11  # the 11 devDependencies in package.json
    assert set(types) == set(DepType)


def test_direct_dependencies_match_package_json():
    g = graph(3)
    direct = {g.nodes[e.child].name: e for e in g.edges if e.parent == ROOT}
    assert direct["express"].dep_type is DepType.PROD
    assert direct["express"].spec == "^4.21.0"
    assert direct["vite"].dep_type is DepType.DEV
    assert len(direct) == 16 + 11


def test_nested_duplicates_are_kept_per_install_path():
    # express 4 pins debug@2.6.9 while the hoisted debug is 4.x, so npm nests
    # copies of debug@2.6.9; the parser keeps each install path (step 5 collapses).
    g = graph(3)
    debug_paths = [p for p, n in g.nodes.items() if (n.name, n.version) == ("debug", "2.6.9")]
    assert len(debug_paths) >= 2
    assert all("/node_modules/debug" in p for p in debug_paths)
    hoisted = g.nodes["node_modules/debug"]
    assert hoisted.version != "2.6.9"


def test_dev_only_packages_carry_the_dev_flag():
    g = graph(3)
    assert g.nodes["node_modules/vite"].dev
    assert not g.nodes["node_modules/express"].dev
