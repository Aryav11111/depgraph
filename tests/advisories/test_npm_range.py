@pytest.mark.parametrize(("spec", "version"), INCLUDE)
def test_node_semver_range_include(spec, version):
    assert satisfies(version, spec) is True


@pytest.mark.parametrize(("spec", "version"), EXCLUDE)
def test_node_semver_range_exclude(spec, version):
    assert satisfies(version, spec) is False


@pytest.mark.parametrize(
    "spec",
    [
        "latest",
        "next",
        "blerg",
        "git+https://github.com/foo/bar.git",
        "github:foo/bar#v1.0.0",
        "foo/bar",
        "file:../local",
        "https://example.com/pkg.tgz",
        "workspace:*",
    ],
)
def test_non_semver_specs_are_unknown_not_false(spec):
    # None, not False: a fix suggestion must not claim "the parent blocks the
    # fix" when we simply can't evaluate the parent's spec.
    assert satisfies("1.2.3", spec) is None
